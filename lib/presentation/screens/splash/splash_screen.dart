// Word-by-word animated tagline
// ─────────────────────────────────────────────────────────────────────
class _AnimatedTagline extends StatelessWidget {
  const _AnimatedTagline({
    required this.text,
    required this.controller,
    required this.baseDelay,
    required this.stagger,
    required this.color,
    required this.fontSize,
    required this.textScaler,
    required this.reduceMotion,
  });

  final String text;
  final AnimationController controller;
  final double baseDelay;
  final double stagger;
  final Color color;
  final double fontSize;
  final TextScaler textScaler;
  final bool reduceMotion;

  @override
  Widget build(BuildContext context) {
    final words = text.split(' ');

    // If reduceMotion is on, show the tagline as a plain text — no stagger.
    if (reduceMotion) {
      return MediaQuery(
        data: MediaQuery.of(context).copyWith(textScaler: textScaler),
        child: Text(
          text,
          textAlign: TextAlign.center,
          style: TextStyle(
            color: color,
            fontSize: fontSize,
            letterSpacing: 0.8,
            fontStyle: FontStyle.italic,
            fontWeight: FontWeight.w500,
          ),
        ),
      );
    }

    return MediaQuery(
      data: MediaQuery.of(context).copyWith(textScaler: textScaler),
      child: Wrap(
        alignment: WrapAlignment.center,
        spacing: 8,
        runSpacing: 4,
        children: List.generate(words.length, (i) {
          final start = baseDelay + (i * stagger);
          final end = (start + 0.25).clamp(0.0, 1.0);
          return AnimatedBuilder(
            animation: controller,
            builder: (context, child) {
              final t =
                  ((controller.value - start) / (end - start)).clamp(0.0, 1.0);
              final curved = Curves.easeOutCubic.transform(t);
              return Opacity(
                opacity: curved,
                child: Transform.translate(
                  offset: Offset(0, 10 * (1 - curved)),
                  child: child,
                ),
              );
            },
            child: Text(
              words[i],
              style: TextStyle(
                color: color,
                fontSize: fontSize,
                letterSpacing: 0.8,
                fontStyle: FontStyle.italic,
                fontWeight: FontWeight.w500,
              ),
            ),
          );
        }),
      ),
    );
  }
}

// ─────────────────────────────────────────────────────────────────────
// Bottom curved wave clipper
// ─────────────────────────────────────────────────────────────────────
class _BottomWaveClipper extends CustomClipper<Path> {
  @override
  Path getClip(Size size) {
    final path = Path();
    path.moveTo(0, size.height * 0.55);
    path.quadraticBezierTo(
      size.width * 0.25,
      size.height * 0.15,
      size.width * 0.5,
      size.height * 0.45,
    );
    path.quadraticBezierTo(
      size.width * 0.75,
      size.height * 0.75,
      size.width,
      size.height * 0.35,
    );
    path.lineTo(size.width, size.height);
    path.lineTo(0, size.height);
    path.close();
    return path;
  }

  @override
  bool shouldReclip(covariant CustomClipper<Path> oldClipper) => false;
}

