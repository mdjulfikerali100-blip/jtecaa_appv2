class _Particle {
  _Particle({
    required this.baseAngle,
    required this.radiusFactor,
    required this.size,
    required this.speed,
    required this.phase,
    required this.colorMix,
  });

  final double baseAngle;
  final double radiusFactor;
  final double size;
  final double speed;
  final double phase;
  final double colorMix;

  factory _Particle.random(math.Random rng) {
    return _Particle(
      baseAngle: rng.nextDouble() * 2 * math.pi,
      radiusFactor: 0.70 + rng.nextDouble() * 0.55,
      size: 1.5 + rng.nextDouble() * 2.0,
      speed: 0.3 + rng.nextDouble() * 0.9,
      phase: rng.nextDouble(),
      colorMix: rng.nextDouble(),
    );
  }
}

class _ParticlePainter extends CustomPainter {
  _ParticlePainter({
    required this.particles,
    required this.progress,
    required this.color,
    required this.secondaryColor,
  });

  final List<_Particle> particles;
  final double progress;
  final Color color;
  final Color secondaryColor;

  @override
  void paint(Canvas canvas, Size size) {
    final center = Offset(size.width / 2, size.height / 2);
    final baseRadius = size.shortestSide * 0.32;

    for (final p in particles) {
      final t = (progress * p.speed + p.phase) % 1.0;

      final angle = p.baseAngle + t * 0.6;
      final radius = baseRadius * p.radiusFactor * (0.9 + t * 0.15);

      final dx = center.dx + math.cos(angle) * radius;
      final dy = center.dy + math.sin(angle) * radius;

      final fade = math.sin(t * math.pi).clamp(0.0, 1.0);
      if (fade <= 0.02) continue;

      final mixed = Color.lerp(color, secondaryColor, p.colorMix)!;
      final paint = Paint()
        ..color = mixed.withValues(alpha: 0.85 * fade)
        ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 1.2);

      canvas.drawCircle(Offset(dx, dy), p.size, paint);

      final haloPaint = Paint()
        ..color = mixed.withValues(alpha: 0.18 * fade)
        ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 6);
      canvas.drawCircle(Offset(dx, dy), p.size * 2.4, haloPaint);
    }
  }

  @override
  bool shouldRepaint(covariant _ParticlePainter old) =>
      old.progress != progress;
}

// ─────────────────────────────────────────────────────────────────────
// Background painter (gradient + grid + orbs + diagonal)
// ─────────────────────────────────────────────────────────────────────
class _SplashBackgroundPainter extends CustomPainter {
  _SplashBackgroundPainter({
    required this.progress,
    required this.entrance,
    required this.navy,
    required this.steelBlue,
    required this.lightBlue,
  });

  final double progress;
  final double entrance;
  final Color navy;
  final Color steelBlue;
  final Color lightBlue;

  @override
  void paint(Canvas canvas, Size size) {
    final bgRect = Offset.zero & size;
    final bgPaint = Paint()
      ..shader = LinearGradient(
        begin: Alignment.topLeft,
        end: Alignment.bottomRight,
        colors: [
          navy,
          Color.lerp(navy, steelBlue, 0.45)!,
          navy,
        ],
        stops: const [0.0, 0.5, 1.0],
      ).createShader(bgRect);
    canvas.drawRect(bgRect, bgPaint);

    final center = Offset(size.width / 2, size.height * 0.40);
    final radius = size.longestSide * 0.75;
    final glowPaint = Paint()
      ..shader = RadialGradient(
        colors: [
          lightBlue.withValues(alpha: 0.18),
          navy.withValues(alpha: 0.0),
        ],
      ).createShader(Rect.fromCircle(center: center, radius: radius));
    canvas.drawCircle(center, radius, glowPaint);

    final gridPaint = Paint()
      ..color = Colors.white.withValues(alpha: 0.03)
      ..strokeWidth = 1;
    const gap = 48.0;
    for (double x = 0; x < size.width; x += gap) {
      canvas.drawLine(Offset(x, 0), Offset(x, size.height), gridPaint);
    }
    for (double y = 0; y < size.height; y += gap) {
      canvas.drawLine(Offset(0, y), Offset(size.width, y), gridPaint);
    }

    final orbs = [
      _Orb(Offset(size.width * 0.12, size.height * 0.18), 100, 0.0, lightBlue),
      _Orb(Offset(size.width * 0.88, size.height * 0.28), 70, 0.35, steelBlue),
      _Orb(Offset(size.width * 0.18, size.height * 0.85), 130, 0.65, steelBlue),
      _Orb(Offset(size.width * 0.92, size.height * 0.82), 80, 0.9, lightBlue),
    ];
    for (final orb in orbs) {
      final t = (progress + orb.phase) % 1.0;
      final dy = (t - 0.5) * 30;
      final paint = Paint()
        ..color = orb.color.withValues(alpha: 0.10)
        ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 40);
      canvas.drawCircle(orb.center.translate(0, dy), orb.radius, paint);
    }

    final linePaint = Paint()
      ..color = lightBlue.withValues(alpha: 0.07)
      ..strokeWidth = 1.2;
    canvas.drawLine(
      Offset(0, size.height * 0.78),
      Offset(size.width, size.height * 0.32),
      linePaint,
    );
  }

  @override
  bool shouldRepaint(covariant _SplashBackgroundPainter old) =>
      old.progress != progress || old.entrance != entrance;
}

class _Orb {
  const _Orb(this.center, this.radius, this.phase, this.color);
  final Offset center;
  final double radius;
  final double phase;
  final Color color;
}
